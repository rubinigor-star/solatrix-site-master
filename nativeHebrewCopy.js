function replaceTextNode(node) {
  const original = node.nodeValue || '';
  let value = original;
  for (const [from, to] of replacements) value = value.split(from).join(to);
  if (value !== original) node.nodeValue = value;
}

function polish(root = document.body) {
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement;
      if (!parent || ['SCRIPT','STYLE','NOSCRIPT','TEXTAREA'].includes(parent.tagName)) return NodeFilter.FILTER_REJECT;
      return /[\u0590-\u05FF]/.test(node.nodeValue || '') ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
    }
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach(replaceTextNode);
  document.documentElement.lang = 'he';
  document.documentElement.dir = 'rtl';
}

const run = () => polish();
if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', run, { once: true });
else run();
new MutationObserver(records => {
  for (const record of records) {
    for (const node of record.addedNodes) {
      if (node.nodeType === Node.TEXT_NODE) replaceTextNode(node);
      else if (node.nodeType === Node.ELEMENT_NODE) polish(node);
    }
  }
}).observe(document.documentElement, { childList: true, subtree: true });
